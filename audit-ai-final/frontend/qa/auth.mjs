import { chromium } from "playwright";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1182, height: 937 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
const base = "http://localhost:3000";
await p.goto(base + "/app", { waitUntil: "networkidle" }); await p.waitForTimeout(800);
console.log("signed-out /app redirects to:", new URL(p.url()).pathname);
await p.goto(base + "/", { waitUntil: "networkidle" }); await p.waitForTimeout(800);
await p.screenshot({ path: "qa/out/auth-out.png", clip: { x: 0, y: 0, width: 1182, height: 72 } });
await p.click(".account .nav__cta"); await p.waitForURL("**/login?mode=signup");
await p.fill("#a-name", "Chahit"); await p.fill("#a-email", "chahit@codeninjas.dev"); await p.fill("#a-password", "secret1");
await p.click("button[type=submit]"); await p.waitForURL("**/app"); await p.waitForTimeout(800);
console.log("workspace says:", (await p.textContent(".auth__who"))?.trim());
await p.screenshot({ path: "qa/out/auth-app.png" });
await p.goto(base + "/", { waitUntil: "networkidle" }); await p.waitForTimeout(800);
console.log("header shows:", (await p.textContent(".account__email"))?.trim());
await p.screenshot({ path: "qa/out/auth-in.png", clip: { x: 0, y: 0, width: 1182, height: 72 } });
await p.click(".account__who"); await p.waitForTimeout(400); await p.screenshot({ path: "qa/out/auth-menu.png", clip: { x: 500, y: 0, width: 682, height: 220 } }); await p.click(".account__menu .link"); await p.waitForTimeout(400);
console.log("after sign out, header has Sign up:", await p.isVisible(".account .nav__cta"), "errors:", errs);
await b.close();
