// Generates the paper/sand grain tokens and writes them into design/tokens.css between the GRAIN markers.
// Usage: node qa/gen-grain.mjs
// Each layer = feTurbulence noise → feColorMatrix that tints it and thresholds its alpha.
// A steep alpha slope (e.g. 17·R − 12) keeps only the noise peaks → isolated particles.
import { readFileSync, writeFileSync } from "node:fs";

const TOKENS = new URL("../../design/tokens.css", import.meta.url);

/** rgb in 0–1, alpha = slope * R + offset (particles) or a * A + b (fine tooth). */
const speck = (id, freq, seed, [r, g, b], slope, offset) =>
  `<filter id='${id}'><feTurbulence type='fractalNoise' baseFrequency='${freq}' seed='${seed}' stitchTiles='stitch'/>` +
  `<feColorMatrix values='0 0 0 0 ${r} 0 0 0 0 ${g} 0 0 0 0 ${b} ${slope} 0 0 0 ${offset}'/></filter>`;
const tooth = (id, freq, octaves, [r, g, b], a, off) =>
  `<filter id='${id}'><feTurbulence type='fractalNoise' baseFrequency='${freq}' numOctaves='${octaves}' stitchTiles='stitch'/>` +
  `<feColorMatrix values='0 0 0 0 ${r} 0 0 0 0 ${g} 0 0 0 0 ${b} 0 0 0 ${a} ${off}'/></filter>`;
const mottle = (id, freq, seed, [r, g, b], a) =>
  `<filter id='${id}'><feTurbulence type='fractalNoise' baseFrequency='${freq}' numOctaves='3' seed='${seed}' stitchTiles='stitch'/>` +
  `<feColorMatrix values='0 0 0 0 ${r} 0 0 0 0 ${g} 0 0 0 0 ${b} ${a} 0 0 0 ${-a * 0.45}'/></filter>`;

const svg = (size, filters) => {
  const defs = filters.join("");
  const rects = filters.map((f) => `<rect width='100%' height='100%' filter='url(#${/id='([^']+)'/.exec(f)[1]})'/>`).join("");
  return `<svg xmlns='http://www.w3.org/2000/svg' width='${size}' height='${size}'>${defs}${rects}</svg>`;
};
const url = (s) =>
  `url("data:image/svg+xml,${s.replace(/</g, "%3C").replace(/>/g, "%3E").replace(/#/g, "%23").replace(/"/g, "'")}")`;

const DEEP = [0.2, 0.12, 0.06];
const INK = [0.33, 0.23, 0.15];
const PAPER = [1, 0.94, 0.85];
const SAND = [0.85, 0.7, 0.55];

// Canvas: soft tonal mottling, fine tooth, dense small dark/light specks, sparse coarse sand grains.
const canvas = svg(360, [
  mottle("m", 0.011, 21, DEEP, 0.22),
  tooth("t", 0.85, 2, [0.19, 0.12, 0.06], 0.6, -0.2),
  speck("d", 0.55, 7, [0.14, 0.08, 0.04], 17, -11.55),
  speck("l", 0.58, 3, PAPER, 17, -12.6),
  speck("cd", 0.24, 13, [0.22, 0.14, 0.08], 22, -16.4),
  speck("cl", 0.26, 29, PAPER, 22, -17.2),
]);

// Dark base (#47331f): sand particles — warm light grains in two sizes, deep pits, mottling.
const dark = svg(360, [
  mottle("m", 0.012, 5, DEEP, 0.4),
  tooth("t", 0.9, 2, [0.12, 0.08, 0.04], 0.6, -0.2),
  speck("s", 0.6, 17, SAND, 17, -11.9),
  speck("p", 0.55, 41, PAPER, 18, -14.1),
  speck("cs", 0.25, 9, SAND, 22, -16.8),
  speck("d", 0.5, 33, DEEP, 17, -11.6),
]);

// Ink grain for pressed letters: transparent except specks, clipped to the glyphs (see .grain-text).
const ink = svg(240, [
  speck("d", 0.62, 4, [0.16, 0.1, 0.05], 15, -9.9),
  speck("l", 0.6, 12, [0.6, 0.46, 0.34], 16, -11.0),
  speck("cd", 0.27, 19, [0.2, 0.13, 0.07], 20, -14.6),
]);

const block = `/* GRAIN:start — generated by frontend/qa/gen-grain.mjs, do not edit by hand */
:root {
  --grain: ${url(canvas)};
  --grain-dark: ${url(dark)};
  --grain-ink: ${url(ink)};
}
/* GRAIN:end */`;

let css = readFileSync(TOKENS, "utf8");
const re = /\/\* GRAIN:start[\s\S]*?GRAIN:end \*\//;
if (re.test(css)) {
  css = css.replace(re, block);
} else {
  css = css.replace(/:root \{\n  --grain: url\([^\n]*\n\}/, block);
}
css = css.replace(
  ".paper--dark { background-color: var(--surface); background-image: var(--grain); }",
  ".paper--dark { background-color: var(--surface); background-image: var(--grain-dark); }",
);
writeFileSync(TOKENS, css);
console.log("grain tokens written", { canvas: canvas.length, dark: dark.length, ink: ink.length });
